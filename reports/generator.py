import os
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from datetime import datetime

def generate_evaluation_report(metrics_data, output_path):
    c = canvas.Canvas(output_path, pagesize=letter)
    width, height = letter

    # Header
    c.setFillColor(colors.HexColor("#0a0a0f"))
    c.rect(0, height - 100, width, 100, fill=1, stroke=0)
    
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 24)
    c.drawString(50, height - 60, "ThreatPulse AI")
    
    c.setFont("Helvetica", 12)
    c.drawString(50, height - 80, "Network Intrusion Detection System - Evaluation Report")
    
    # Date
    c.setFillColor(colors.black)
    c.setFont("Helvetica", 10)
    current_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    c.drawString(50, height - 120, f"Generated on: {current_time}")

    # Section 1: Metrics
    c.setFont("Helvetica-Bold", 16)
    c.drawString(50, height - 160, "1. Model Evaluation Metrics")
    
    c.setFont("Helvetica", 12)
    y_pos = height - 190
    if metrics_data:
        c.drawString(70, y_pos, f"Accuracy:  {metrics_data.get('accuracy', 'N/A')}")
        c.drawString(70, y_pos - 20, f"Precision: {metrics_data.get('precision', 'N/A')}")
        c.drawString(70, y_pos - 40, f"Recall:    {metrics_data.get('recall', 'N/A')}")
        c.drawString(70, y_pos - 60, f"F1-Score:  {metrics_data.get('f1_score', 'N/A')}")
        c.drawString(70, y_pos - 80, f"Total Test Records: {metrics_data.get('total_records', 'N/A')}")
        
        # Confusion Matrix Image
        image_path = os.path.join(os.path.dirname(__file__), '..', 'frontend', 'static', 'confusion_matrix.png')
        if os.path.exists(image_path):
            c.setFont("Helvetica-Bold", 16)
            c.drawString(50, y_pos - 130, "2. Confusion Matrix")
            c.drawImage(image_path, 150, y_pos - 380, width=300, height=250)
    else:
        c.drawString(70, y_pos, "No metrics data available.")

    # Footer
    c.setFont("Helvetica-Oblique", 9)
    c.drawString(50, 30, "This report was automatically generated by ThreatPulse AI.")
    
    c.save()
    return output_path